/**
 * Шейдеры. Характер материала взят из Dreamzone: медленное движение
 * с длинным хвостом, зернистость, ничего не отскакивает. Палитра
 * своя и постоянная — уголь и пыльно-голубой.
 *
 * Радиальных размытых пятен здесь нет намеренно: именно они делают
 * фон похожим на CSS-градиент из шаблона.
 */

const NOISE = `
float hash(vec2 p){ return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453123); }
float noise(vec2 p){
  vec2 i = floor(p), f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(mix(hash(i), hash(i + vec2(1,0)), u.x),
             mix(hash(i + vec2(0,1)), hash(i + vec2(1,1)), u.x), u.y);
}
float fbm(vec2 p, float oct){
  float s = 0.0, a = 0.5;
  for (int i = 0; i < 5; i++){
    if (float(i) >= oct) break;
    s += a * noise(p);
    p *= 2.03;
    a *= 0.5;
  }
  return s;
}`;

export const FIELD_VERT = `
varying vec2 vUv;
void main(){
  vUv = uv;
  gl_Position = vec4(position.xy, 0.0, 1.0);
}`;

export const FIELD_FRAG = `
precision highp float;
varying vec2 vUv;
uniform vec2  uRes;
uniform float uTime;
uniform float uOct;
uniform float uEnter;
/* След руки: восемь последних положений и вес каждого по возрасту.
   Одна точка курсора даёт «фонарик», след — ощущение, что материал
   помнит движение. */
uniform vec2  uTrail[8];
uniform float uTrailW[8];
uniform vec3  uVoid;
uniform vec3  uAzure;
uniform float uSpeed;
/** Указатель в UV — центр линзы, гнущей материал. */
uniform vec2  uLens;
uniform float uDrag;
uniform float uHasPtr;

${NOISE}

void main(){
  vec2 uv = vUv;
  float aspect = uRes.x / max(uRes.y, 1.0);

  // Линза. Рука не сыплет частицы поверх картинки, а гнёт саму среду:
  // координаты под курсором стягиваются к нему, и рисунок материала
  // тянется, как стекло. Это то же семейство приёмов, что «жидкое
  // стекло» в Dreamzone, и оно не читается как накладной эффект.
  vec2 toLens = vec2((uv.x - uLens.x) * aspect, uv.y - uLens.y);
  float lensDist = length(toLens);
  float pull = exp(-lensDist * 3.2) * (0.055 + uDrag * 0.16) * uHasPtr;
  vec2 warped = uv - normalize(toLens + vec2(0.0001)) * pull * vec2(1.0 / aspect, 1.0);

  vec2 p = vec2(warped.x * aspect, warped.y);

  // Время идёт медленно: материал дышит, а не бурлит.
  float t = uTime * 0.035;
  float n = fbm(p * 1.5 + vec2(t, -t * 0.7), uOct);
  n = fbm(p * 1.9 + vec2(n * 0.5, n * 0.35 - t * 0.5), uOct);

  // Возмущение от следа руки. Ближе и свежее — сильнее.
  float stir = 0.0;
  for (int i = 0; i < 8; i++){
    vec2 d = vec2((uTrail[i].x - uv.x) * aspect, uTrail[i].y - uv.y);
    float dist = length(d);
    stir += uTrailW[i] * exp(-dist * 3.4);
  }
  stir = clamp(stir, 0.0, 1.4);

  // Свет приходит косо сверху-справа, как в сцене Dreamzone.
  // Радиального свечения по центру здесь нет намеренно: круглое
  // размытое пятно под текстом — самая узнаваемая примета шаблона.
  float slope = clamp((uv.x * 0.55 + uv.y * 0.75) - 0.15, 0.0, 1.0);

  // Под самой линзой материал ещё и светлеет — как утолщение стекла.
  float lensGlow = exp(-lensDist * 4.5) * uHasPtr * (0.10 + uDrag * 0.22);

  float body = n * 0.72 + stir * 0.55 + uSpeed * 0.35;
  vec3 col = mix(uVoid, uAzure, clamp(body * 0.30 * (0.35 + slope * 0.85), 0.0, 1.0));

  // Прожилки: тонкие светлые линии по градиенту шума — они читаются
  // как материал, а не как заливка.
  // Прожилка одна и еле заметная. На большем контрасте фон
  // читается как мраморная плитка, а не как материал под стеклом.
  float vein = smoothstep(0.50, 0.55, n) - smoothstep(0.55, 0.61, n);
  col += uAzure * vein * 0.035 * slope;

  col += uAzure * lensGlow;
  col *= uEnter;

  gl_FragColor = vec4(col, 1.0);
}`;

export const PARTICLE_VERT = `
precision highp float;
attribute vec2 aBase;
attribute vec2 aFrom;
attribute float aSeed;
uniform vec2  uRes;
/* Поле течения — след, который рука оставляет в воздухе.

   Рука не давит на точки сама: она вносит импульс в поле, а поле
   затухает. Стоящий курсор не вносит ничего, поэтому пустоты вокруг
   него не бывает вовсе — возмущение рождается только движением. */
attribute vec3 aDisp;
/** Скорость точки в пикселях за кадр — по ней она вытягивается в штрих. */
attribute vec3 aVel;
uniform float uTime;
uniform float uEnter;
uniform float uPixelRatio;
uniform float uDrag;
uniform vec2  uDragVec;
/** 0 — камера на точке заголовка, 1 — ушла на следующую. */
uniform float uDepart;
/** Где камера сейчас и где стояла в начале: по ним точка переводится
    в экранные пиксели, чтобы рука работала на любом угле поворота. */
uniform float uCamZ;
uniform float uBaseZ;
/** Доворот самого слова: на нём облако «ложится» на место, а не влетает
    в неподвижную мишень. */
uniform float uWordSpin;
/** Половина ширины облака в пикселях: по ней считается очередь на оборот. */
uniform float uHalfW;
varying float vFade;
varying float vSpark;
/** Направление движения и длина штриха — фрагменту, чтобы вытянуть точку. */
varying vec2 vDir;
varying float vStretch;
varying float vHeat;

void main(){
  // Появление: частица прилетает из своей случайной точки на место.
  // Разброс по aSeed, чтобы облако собиралось не одним фронтом.
  float d = clamp((uEnter - aSeed * 0.35) / 0.65, 0.0, 1.0);
  float e = 1.0 - pow(1.0 - d, 3.0);
  vec2 sheet = mix(aFrom, aBase, e);

  // Собственное дыхание — мелкое, иначе текст «плывёт» и читается хуже.
  // Частоты у каждой точки свои, иначе всё облако качается в такт.
  float w1 = 0.38 + fract(aSeed * 7.13) * 0.5;
  float w2 = 0.33 + fract(aSeed * 3.71) * 0.45;
  sheet.x += sin(uTime * w1 + aSeed * 6.28) * 1.25;
  sheet.y += cos(uTime * w2 + aSeed * 5.14) * 1.25;

  // Микротолщина облака. Надпись плоская, и без глубины на четверти
  // оборота она схлопывается в линию и пропадает с экрана целиком.
  float z0 = (fract(aSeed * 43.758) - 0.5) * 130.0;

  /* Очередь на оборот.

     Раньше все точки поворачивались одной фазой, и как бы ни рассыпалась
     надпись, было видно, что вертится плита. Теперь точка заходит на
     оборот в свой черёд: очередь идёт слева направо, буква за буквой,
     плюс личный разброс — без него фронт виден ровной вертикальной
     границей. */
  float xs = clamp(aBase.x / max(uHalfW, 1.0) * 0.5 + 0.5, 0.0, 1.0);
  float rotWait = xs * 0.34 + fract(aSeed * 7.77) * 0.16;
  float rt = clamp((uDepart - rotWait) / max(1.0 - rotWait, 0.08), 0.0, 1.0);
  // Разгон по экспоненте: трогается еле-еле и к концу летит.
  // К обороту по маршруту добавляется раскрутка рукой: зажатой мышью
  // слово можно провернуть на сколько угодно, и оно докрутится по
  // инерции само.
  float a = 3.14159 * pow(rt, 2.1);
  float ca = cos(a), sa = sin(a);

  // Точка не сидит на жёсткой окружности, а поджимается к оси на
  // разгоне и снова уходит наружу: так она объезжает ось, как на
  // гравитационном манёвре, а не едет по стрелке циферблата.
  float swing = 1.0 - 0.28 * sin(a) * (0.6 + fract(aSeed * 5.19) * 0.8);
  // Глубину поворота поджимаем. На полной ближняя половина слова
  // вылезает на камеру раньше, чем успевает провернуться, и движение
  // читается как разворот в три четверти, а не как вращение вокруг оси.
  /* Слово доворачивается вместе с точками.

     Дом раньше стоял намертво, и последняя часть сборки читалась как
     влёт в неподвижную мишень: точки шли по дуге, а цель не двигалась.
     Теперь на отдаче поворачивается и сама надпись — и садится на место
     по той же закрученной траектории, как лист, который кладут на стол. */
  float cw = cos(uWordSpin);
  float sw = sin(uWordSpin);
  float hx = sheet.x * cw - z0 * sw;
  float hz = sheet.x * sw + z0 * cw;
  /* Наклона вокруг горизонтали здесь намеренно нет.

     Он был: слово заодно заваливалось вперёд-назад. Вместе с поворотом
     вокруг вертикали это читалось как вращение в плоскости экрана —
     всегда против часовой, куда бы рука ни крутила. Ось одна,
     вертикальная, и движение по ней должно быть чистым. */

  vec3 P = vec3(hx * ca * swing + hz * sa,
                sheet.y,
                (-hx * sa * swing + hz * ca) * 0.42);

  // Срыв по касательной к вращению: точку тянет само движение.
  vec2 tang = normalize(vec2(P.z, -P.x) + vec2(0.0001));
  float spill = smoothstep(0.34, 1.0, uDepart) * (55.0 + aSeed * 300.0);
  P.x += tang.x * spill;
  P.z += tang.y * spill;
  // Чуть-чуть по высоте, иначе россыпь идёт ровным поясом.
  P.y += (fract(aSeed * 91.317) - 0.5) * spill * 0.3;

  // Полёт в камеру. У каждой точки своё время старта и своя дальность,
  // иначе облако идёт на зрителя плитой и бьёт в объектив кирпичом.
  // Разлёта от центра наружу здесь нет намеренно — он выедал середину,
  // и облако читалось бубликом с чёрной дырой посередине.
  // Слово целиком идёт на камеру, пока вертится. Без этого оно крутится
  // на месте, и до зрителя доезжают одни сорвавшиеся точки, а сама
  // надпись так и остаётся вдали.
  P.z += pow(uDepart, 2.0) * 900.0;

  // Дождь: сперва срывается одна точка, за ней вторая, потом гуще
  // и гуще. Степень ниже единицы скашивает раздачу к концу — при
  // равной раздаче ливень шёл с первой секунды и весь разом.
  float delay = pow(fract(aSeed * 17.317), 0.38) * 0.72;
  float fly = smoothstep(delay, delay + 0.3, uDepart);
  P.z += fly * (950.0 + aSeed * 1500.0);

  /* Рука работает по экрану, а не по исходной раскладке слова.

     Раньше отталкивание считалось до поворота: на развороте в 180°
     ось X смотрит в другую сторону, и точки уходили в зеркальную
     сторону от курсора — вместо магнита получался антимагнит. Теперь
     точка сперва переводится в экранные пиксели, там встречается
     с курсором, и уже сдвиг возвращается обратно в сцену. */
  float depth = max(uCamZ - P.z, 60.0);
  float persp = uBaseZ / depth;
  vec2 screen = P.xy * persp;

  /* Никакого потолка сдвига здесь больше нет.

     Он и был тем «пределом», за который точка не могла отлететь, сколько
     по ней ни води: сдвиг обрезался, и повторный проход рукой ничего не
     добавлял. Теперь дальность решает сама физика на стороне JS — точка
     летит, пока её не погасит трение, и удары складываются. */
  P.xy += aDisp.xy / persp;
  P.z += aDisp.z;

  // Поблёскивание: у каждой точки своя редкая короткая вспышка. Степень
  // синуса держит её тёмной почти всё время — получается искра, а не
  // общая пульсация, от которой надпись «дышит» целиком и мельтешит.
  vSpark = pow(max(0.0, sin(uTime * 0.75 + aSeed * 61.7)), 14.0);

  /* Смаз по скорости.

     Летящая точка вытягивается вдоль своего движения и сжимается обратно,
     когда замирает. Без этого песок всё время одинаково круглый: глаз
     видит, что точки переместились, но скорости не чувствует — движение
     выходит вялым, сколько его ни усиливай. */
  float spd = length(aVel.xy);
  vStretch = 1.0 + min(spd * 0.22, 4.0);
  vDir = spd > 0.01 ? aVel.xy / spd : vec2(1.0, 0.0);
  // На лету точка ещё и разогревается: песок на скорости светлее.
  vHeat = min(spd * 0.05, 0.65);

  vFade = e * (1.0 - smoothstep(0.82, 1.0, uDepart));
  vec4 mv = modelViewMatrix * vec4(P, 1.0);
  gl_Position = projectionMatrix * mv;
  // Точка растёт по мере приближения к камере. Без этого летящая в лицо
  // частица остаётся такой же мелкой, и полёта не чувствуется вовсе.
  // Квадрат под точку растёт вместе со штрихом, иначе он обрежется краем.
  gl_PointSize = (1.35 + aSeed * 0.85) * uPixelRatio * clamp(persp, 0.3, 3.0)
               * (1.0 + vSpark * 0.5) * vStretch;
}`;

export const PARTICLE_FRAG = `
precision highp float;
uniform vec3 uSand;
varying float vFade;
varying float vSpark;
varying vec2 vDir;
varying float vStretch;
varying float vHeat;

void main(){
  // Мягкий круг вместо квадратной точки: квадраты выдают WebGL сразу.
  // В покое это круг, на скорости — капсула, вытянутая по ходу движения:
  // квадрат под точку уже увеличен, и здесь остаётся сжать координаты
  // поперёк хода, чтобы получился штрих, а не раздутое пятно.
  vec2 c = gl_PointCoord - 0.5;
  vec2 along = vec2(dot(c, vDir), dot(c, vec2(-vDir.y, vDir.x)));
  along.x /= vStretch;
  float a = 1.0 - smoothstep(0.28 / vStretch, 0.5 / vStretch, length(along));
  if (a < 0.01) discard;
  // Точки стоят плотно, и на полной непрозрачности буква заливается
  // сплошняком. Чуть прозрачнее — слово читается цельным, но видно,
  // что оно набрано из точек.
  vec3 col = mix(uSand, vec3(1.0), vSpark * 0.55 + vHeat);
  // Растянутый штрих тоньше по яркости: иначе быстрая точка выглядит
  // жирнее остальных и облако на движении выцветает в кашу.
  gl_FragColor = vec4(col, a * vFade * (0.72 + vSpark * 0.28) / (0.6 + vStretch * 0.4));
}`;
