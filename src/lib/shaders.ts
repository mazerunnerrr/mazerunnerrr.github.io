export const FIELD_FRAG = `
precision highp float;
varying vec2 vUv;
uniform vec2  uRes;
uniform float uTime;
uniform float uOct;
uniform float uEnter;
uniform vec3  uVoid;
uniform vec3  uAzure;
uniform float uSpeed;
/* Вода, которую мешает рука (\`Water\` в fluid.ts): rg — насколько сдвинута
   вода, px; b — муть; a — скорость течения. Илья выбрал все три слоя
   разом: муть, свет сверху и взвесь (2026-10-19). */
uniform sampler2D uWaterTex;
uniform vec4  uWaterMap;
/** Свет главы: у каждой точки маршрута своя подсветка с одной стороны. */
uniform vec3  uTint;
uniform float uTintAmt;
uniform vec2  uTintDir;

${NOISE}

void main(){
  vec2 uv = vUv;
  float aspect = uRes.x / max(uRes.y, 1.0);

  /* Мы в толще воды (Илья, 2026-10-19). Рука не светит фонариком —
     прежняя линза с подсветкой под курсором читалась «высвечиванием», —
     а мешает воду: всё, что в толще, сдвигается вместе с ней и медленно
     возвращается, когда вода успокоится. */
  vec4 wt = texture2D(uWaterTex, uv * uWaterMap.xy + uWaterMap.zw);
  vec2 wuv = uv - wt.xy / uRes;
  vec2 p = vec2(wuv.x * aspect, wuv.y);

  // Время идёт медленно: вода дышит, а не бурлит.
  float t = uTime * 0.035;
  float n = fbm(p * 1.5 + vec2(t, -t * 0.7), uOct);
  n = fbm(p * 1.9 + vec2(n * 0.5, n * 0.35 - t * 0.5), uOct);

  /* Полночный синий ровным цветом: сверху на тон светлее, книзу глубже.

     Раньше фон был углём с пыльно-голубыми разводами, прожилками и косым
     светом — Илья забраковал «оттенки» (2026-10-16). Шум остался едва
     заметным дыханием, а всё остальное появляется только от руки. */
  vec3 col = mix(uVoid * 0.82, uVoid * 1.18, smoothstep(0.0, 1.0, uv.y));
  col += uAzure * (n - 0.5) * 0.03;
  col += uAzure * uSpeed * 0.07;

  /* Муть: рука поднимает со дна взвесь, она клубится по течению и долго
     оседает. Само облако несёт поле в JS, здесь ему дают зерно — рыхлые
     клочья, а не гладкое пятно. */
  float grain = fbm(p * 7.0 + vec2(n * 1.2, -t * 2.0), 4.0);
  // Гребни шума — тонкие волокна, как взбаламученный ил, а не пятно света.
  float wisp = pow(1.0 - abs(grain * 2.0 - 1.0), 4.0);
  float silt = min(wt.z, 1.0) * wisp;
  col += uAzure * silt * 0.3;

  /* Свет сверху: мягкие косые лучи от далёкой поверхности, к глубине
     гаснут. Вода, сдвинутая рукой, их гнёт — видно, что толща живая. */
  float sx = wuv.x * aspect + (1.0 - wuv.y) * 0.32;
  float rays = fbm(vec2(sx * 2.6, wuv.y * 0.35 + t * 0.6), 4.0);
  rays = smoothstep(0.42, 0.8, rays) * smoothstep(0.05, 1.0, wuv.y);
  col += uAzure * rays * 0.075;

  /* Свет главы — заливка от края экрана, а не пятно: радиальное свечение
     по центру — примета шаблона. Степень держит свет у своего края. */
  float wash = clamp(dot(uv - 0.5, uTintDir) + 0.5, 0.0, 1.0);
  col += uTint * uTintAmt * pow(wash, 2.4);
  // Появление — из ровного синего, а не из чёрного: фон страницы того же
  // цвета, и при загрузке не мигает.
  col = mix(uVoid, col, uEnter);

  gl_FragColor = vec4(col, 1.0);
}`;

export const PARTICLE_VERT = `
precision highp float;
/* Два дома точки: объект, каким он стоит на аллее (A), и каким раскрывается
   в своей комнате (B). Колесо между ними не переключает — только вход
   в комнату, и то во времени, а не от прокрутки. */
attribute vec3 aHomeA;
attribute vec3 aHomeB;
/** Где эта точка стоит у соседа, в которого форма пересобирается на месте
    (контакты → имя); у остальных — свой же дом. */
attribute vec3 aOther;
attribute vec2 aFrom;
attribute float aSeed;
/** 1 — точка видна и внутри раскрытой сферы, 0.5 — внутри гаснет.
    У надписей — 1. */
attribute float aKeep;
uniform vec2  uRes;
/* Поле течения — след, который рука оставляет в воздухе.

   Рука не давит на точки сама: она вносит импульс в поле, а поле
   затухает. Стоящий курсор не вносит ничего, поэтому пустоты вокруг
   него не бывает вовсе — возмущение рождается только движением. */
attribute vec3 aDisp;
/** Скорость точки в пикселях за кадр — по ней она вытягивается в штрих. */
attribute vec3 aVel;
uniform float uTime;
uniform float uEnter;
uniform float uPixelRatio;
/** Раскрытие в комнату: 0 — объект на аллее, 1 — в своей комнате. */
uniform float uMorph;
/** Сборка и уход: 0 — объект собран перед зрителем, −1 — его точки ещё
    в глубине (подлёт), +1 — уже пролетели сквозь камеру (уход). */
uniform float uPass;
/** Видимость: пока открыта комната, остальной мир гаснет. */
uniform float uVis;
/** Притушить объект под текстом комнаты, чтобы буквы читались. */
uniform float uDim;
/** Где камера сейчас и где стояла в начале: по ним точка переводится
    в экранные пиксели, чтобы рука работала на любом угле поворота. */
uniform float uCamZ;
uniform float uBaseZ;
/** Половина ширины облака в пикселях: по ней считается очередь на оборот. */
uniform float uHalfWA;
uniform float uHalfWB;
/* Объём. Надпись плоская: ей нужна лишь микротолщина (uThick), а глубина
   поворота поджата (uDepth 0.42). Сфера объёмная по-настоящему: толщина
   ей не нужна, глубина — целиком, и она медленно вращается вокруг своего
   центра (uSpin), который в комнате уезжает к зрителю (uCzA → uCzB). */
uniform float uThick;
uniform float uDepth;
/** Поворот объёмной формы: сфера крутится сама и рукой в любую сторону. */
uniform mat3  uRot;
uniform float uCzA;
uniform float uCzB;
/** Раскрытие: надпись идёт волной с отрывом от плоскости (uLag, uLift),
    сетка сферы — разом и ровно, точки только расходятся. */
uniform float uLag;
uniform float uLift;
/** Объёмная форма — сфера: раскрывается не по прямой между домами,
    а как раскладная игрушка. */
uniform float uSolid;
/** Пересборка сферы в соседнюю: +уход, −приход, 0 — сфера на месте. */
uniform float uSwap;
/** Как объект уходит или прилетает на аллее, своё у каждого и у каждой
    стороны (Илья, 2026-10-20): 0 — разворот очередью и дождь в камеру;
    1 — «в камеру»: точки по очереди с разгоном летят по своим лучам к зрителю,
    как прыжок на скорость света; 2 — «стяжка»: точки влетают из-за краёв
    экрана и садятся на форму разом; 3 — «разлёт»: шар раскручивается, и точки
    уходят во все стороны. */
uniform float uFlow;
/* Кадр проекта на сфере — маской. Картинка спроецирована спереди и стоит
   неподвижно, а точки вращающейся сферы проходят сквозь неё и берут из неё
   свет: кадр проступает на материи, как отражение в кристалле. Два кадра
   и доля перехода — чтобы скриншоты сменяли друг друга без скачка. */
uniform sampler2D uTex0;
uniform sampler2D uTex1;
uniform float uTexMix;
/** Насколько кадр виден: 0 — у объекта нет кадра или он в комнате. */
uniform float uTexAmt;
/** Ширина кадра к высоте: кадр накрывает сферу целиком, лишнее по краям обрезано. */
uniform float uTexAspect;
/** Поправка на среднюю яркость кадра: все сферы выходят одного уровня. */
uniform float uTexGain;
uniform vec3  uSand;
varying vec3 vBase;
/** Сколько света точке даёт кадр: тёмное место кадра гасит её почти совсем. */
varying float vMask;
varying float vFade;
varying float vSpark;
/** Направление движения и длина штриха — фрагменту, чтобы вытянуть точку. */
varying vec2 vDir;
varying float vStretch;
varying float vHeat;

void main(){
  /* Раскрытие в комнату — у каждой точки в свой черёд.

     Все сразу дали бы плиту, которая плавно растягивается; с разбросом
     материя расходится волной, а пока точка в пути, она отрывается
     от плоскости к зрителю и ложится обратно уже на новом месте. */
  float lag = fract(aSeed * 13.13) * uLag;
  float m = clamp((uMorph - lag) / (1.0 - uLag), 0.0, 1.0);
  // Ход раскрытия сглажен в JS — у сферы UNFOLD_CURVE, у облака «обо мне»
  // своя кривая (Scene.tsx); здесь сглаживаем только формы с очередью.
  if (uLag > 0.0) m = m * m * (3.0 - 2.0 * m);
  vec3 home3 = mix(aHomeA, aHomeB, m);
  /* Раскрытие сферы — в два движения, как у раскладной игрушки: сперва
     сетка растёт на месте, до двух с половиной раз, и видна целиком; лишь
     на последней трети хода надвигается на зрителя, и ты внутри. По прямой
     между домами она на полпути уже вылезала за экран. */
  float mc = m;
  if (uSolid > 0.5) {
    /* Одно сплошное движение: радиус растёт по экспоненте — каждый миг
       сетка становится больше в одно и то же число раз, и в перспективе
       это читается ровным раскрытием. В два этапа выходило два рывка
       с паузой между ними (Илья, 2026-10-18). */
    vec3 dir = aHomeA / max(uHalfWA, 1.0);
    home3 = dir * uHalfWA * pow(uHalfWB / max(uHalfWA, 1.0), m);
    mc = m * m;
  }

  /* Пересборка сферы в соседнюю — волной снизу вверх. Сетка у всех сфер
     одна и та же: точка уходящего проекта отрывается от своего места,
     проворачивается вдоль широты и гаснет, а на её месте так же, из
     поворота, садится точка следующего — уже с его кадром. Шар не
     пропадает ни на миг, но к концу волны на нём другой проект. */
  float swapVis = 1.0;
  /** Вспышка точки в пути: волна пересборки светится, как песок под кистью. */
  float swapGlow = 0.0;
  if (uSwap != 0.0 && uSolid < 0.5) {
    /* Пересборка надписи в соседнюю на месте: «@» перетекает в имя, и круг
       замыкается — понятно, что вернулись к началу (Илья, 2026-10-20). Весь
       путь ведёт уходящая надпись: точки в свой черёд переходят на места
       букв соседа, по пути приподнимаясь к зрителю. Приходящая не видна,
       пока не совпадёт с ней точка в точку, и сменяет её незаметно. */
    float rph = uSwap > 0.0 ? uSwap : 1.0 + uSwap;
    float rst = fract(aSeed * 7.77) * 0.35;
    float rk = smoothstep(0.0, 1.0, clamp((rph - rst) / 0.65, 0.0, 1.0));
    home3 = mix(home3, aOther, rk);
    home3.z += sin(rk * 3.14159) * (80.0 + fract(aSeed * 29.7) * 220.0);
    swapGlow = sin(rk * 3.14159) * 0.5;
    // Передача встык: уходящая прячется на 0.999 пути (away в Scene.tsx),
    // приходящая видна с того же места. Прежде она проявлялась только ровно
    // на точке, и пока доводка доползала последнюю тысячную, не было видно
    // ни той, ни другой — имя мигало после остановки.
    swapVis = uSwap > 0.0 ? 1.0 : step(0.999, rph);
  } else if (uSwap != 0.0) {
    float R0 = max(uHalfWA, 1.0);
    // Порог каждой точки — в [0.11, 0.87], ширина перехода ±0.1: волна
    // начинается после старта и заканчивается до конца пути. Раньше верхние
    // точки не успевали сесть и в последний миг встали скачком.
    float th = 0.16 + 0.66 * (0.5 + 0.5 * home3.y / R0) + (fract(aSeed * 9.17) - 0.5) * 0.1;
    float ph = uSwap > 0.0 ? uSwap : 1.0 + uSwap;
    float l = smoothstep(th - 0.1, th + 0.1, ph);
    float off = uSwap > 0.0 ? l : 1.0 - l;
    swapGlow = sin(off * 3.14159);
    swapVis = uSwap > 0.0 ? 1.0 - l : l;
    float tw = off * 1.1 * sign(uSwap);
    float c2 = cos(tw), s2 = sin(tw);
    home3 = vec3(home3.x * c2 + home3.z * s2, home3.y, -home3.x * s2 + home3.z * c2)
          * (1.0 + 0.22 * sin(off * 3.14159));
  }
  // Поворот объёмной формы вокруг своего центра. У плоской — единичный.
  vec3 hr = uRot * home3;
  vec2 home = hr.xy;
  float homeZ = hr.z;
  float halfW = mix(uHalfWA, uHalfWB, m);
  float lift = sin(m * 3.14159) * (60.0 + fract(aSeed * 29.7) * 260.0) * uLift;

  /* Свет из кадра проекта. Проекция — по экранным X и Y, поэтому кадр
     читается прямо, как бы ни повернулась сфера. Задняя половина видна
     сквозь переднюю и светится слабее — так шар остаётся шаром. */
  float R = max(uHalfWA, 1.0);
  vec2 tuv = vec2(home.x / (2.0 * R * uTexAspect) + 0.5, home.y / (2.0 * R) + 0.5);
  vec3 tex = min(mix(texture2D(uTex0, tuv).rgb, texture2D(uTex1, tuv).rgb, uTexMix) * uTexGain, vec3(1.0));
  float lum = dot(tex, vec3(0.299, 0.587, 0.114));
  float face = mix(0.55, 1.0, smoothstep(-0.5, 0.6, homeZ / R));
  float shown = uTexAmt * (1.0 - m);
  /* Кадр читается контрастом: светлое в нём горит ярче песка, тёмное
     притушено. Но сетка видна всегда — это сам объект, кадр лишь
     проступает на ней (Илья, 2026-10-18); на тёмной заглушке с прежним
     порогом сфера оставалась одним ободом. Край светится, как у голограммы. */
  float rim = pow(1.0 - abs(homeZ / R), 3.0);
  // Сетка видна всегда — пол держит её и на тёмной заглушке, —
  // а светлое в кадре горит на ней ярче.
  /* Цвет — в основном песок сайта, кадр лишь тонирует; яркость к среднему
     уровню приведена через uTexGain, светлое место кадра горит чуть ярче.
     Иначе светлый скриншот давал белую сферу ярче заголовка, тёмный —
     почти чёрную (Илья, 2026-10-18). */
  vec3 lit = mix(uSand, tex, 0.2) * (1.0 + pow(lum, 1.4) * 0.45);
  vBase = mix(uSand, mix(lit, uSand, rim * 0.6), shown);
  vMask = mix(1.0, max((0.9 + 0.1 * smoothstep(0.05, 0.8, lum)) * face, rim), shown);

  /* Сборка и уход по центру, как было у одного мира: на подлёте точки
     приходят из глубины, на уходе — разворот, срыв, дождь в камеру.
     Объект не въезжает сбоку — Илья забраковал это 2026-10-16. */
  float depart = abs(uPass);
  float toward = uPass < 0.0 ? -1.0 : 1.0;

  // Появление: частица прилетает из своей случайной точки на место.
  // Разброс по aSeed, чтобы облако собиралось не одним фронтом.
  float d = clamp((uEnter - aSeed * 0.35) / 0.65, 0.0, 1.0);
  float e = 1.0 - pow(1.0 - d, 3.0);
  vec2 sheet = mix(aFrom, home, e);

  // Собственное дыхание — мелкое, иначе текст «плывёт» и читается хуже.
  // Частоты у каждой точки свои, иначе всё облако качается в такт.
  float w1 = 0.38 + fract(aSeed * 7.13) * 0.5;
  float w2 = 0.33 + fract(aSeed * 3.71) * 0.45;
  // У сетки сферы дыхание почти убрано: на треугольнике в полтора
  // десятка пикселей оно размывало линии в шум.
  float breath = mix(1.25, 0.2, uSolid);
  sheet.x += sin(uTime * w1 + aSeed * 6.28) * breath;
  sheet.y += cos(uTime * w2 + aSeed * 5.14) * breath;

  // Микротолщина облака. Надпись плоская, и без глубины на четверти
  // оборота она схлопывается в линию и пропадает с экрана целиком.
  float z0 = (fract(aSeed * 43.758) - 0.5) * uThick + lift + homeZ;

  /* Очередь на оборот.

     Раньше все точки поворачивались одной фазой, и как бы ни рассыпалась
     надпись, было видно, что вертится плита. Теперь точка заходит на
     оборот в свой черёд: очередь идёт слева направо, буква за буквой,
     плюс личный разброс — без него фронт виден ровной вертикальной
     границей. */
  float xs = clamp(home.x / max(halfW, 1.0) * 0.5 + 0.5, 0.0, 1.0);
  float rotWait = xs * 0.34 + fract(aSeed * 7.77) * 0.16;
  float rt = clamp((depart - rotWait) / max(1.0 - rotWait, 0.08), 0.0, 1.0);
  // Разгон по экспоненте: трогается еле-еле и к концу летит.
  // На подлёте оборот зеркальный: объект доворачивается туда же, куда
  // уходил прежний, и полтора оборота читаются одним движением.
  float a = toward * 3.14159 * pow(rt, 2.1);
  float ca = cos(a), sa = sin(a);

  // Точка не сидит на жёсткой окружности, а поджимается к оси на
  // разгоне и снова уходит наружу: так она объезжает ось, как на
  // гравитационном манёвре, а не едет по стрелке циферблата.
  float swing = 1.0 - 0.28 * sin(a) * (0.6 + fract(aSeed * 5.19) * 0.8);
  // Поворот слова рукой уже в uRot: дом повёрнут целиком, в любую сторону.
  float hx = sheet.x;
  float hz = z0;

  vec3 P = vec3(hx * ca * swing + hz * sa,
                sheet.y,
                (-hx * sa * swing + hz * ca) * uDepth + mix(uCzA, uCzB, mc));

  // Срыв по касательной к вращению: точку тянет само движение.
  vec2 tang = normalize(vec2(P.z, -P.x) + vec2(0.0001));
  float spill = smoothstep(0.34, 1.0, depart) * (55.0 + aSeed * 300.0);
  P.x += tang.x * spill;
  P.z += tang.y * spill;
  // Чуть-чуть по высоте, иначе россыпь идёт ровным поясом.
  P.y += (fract(aSeed * 91.317) - 0.5) * spill * 0.3;

  // Полёт в камеру. У каждой точки своё время старта и своя дальность,
  // иначе облако идёт на зрителя плитой и бьёт в объектив кирпичом.
  P.z += toward * pow(depart, 2.0) * 900.0;

  // Дождь: сперва срывается одна точка, за ней вторая, потом гуще
  // и гуще. Степень ниже единицы скашивает раздачу к концу — при
  // равной раздаче ливень шёл с первой секунды и весь разом.
  float delay = pow(fract(aSeed * 17.317), 0.38) * 0.72;
  float fly = smoothstep(delay, delay + 0.3, depart);
  P.z += toward * fly * (950.0 + aSeed * 1500.0);

  /* Свои переходы (uFlow). Без разворота: форма не крутится плитой, каждая
     точка идёт своим путём от места, где стоит. Точки остаются точками —
     смаз в штрихи на лету выглядел размытыми овалами (Илья, 2026-10-20). */
  float flowFade = 1.0;
  if (uFlow > 0.5 && depart > 0.0) {
    vec3 P0 = vec3(hx, sheet.y, hz * uDepth + mix(uCzA, uCzB, mc));
    float rnd = fract(aSeed * 17.317);
    // Очередь, как у прежнего дождя: сперва срываются единицы, потом всё
    // гуще, и в конце уходят все разом. Путь каждой — с разгоном.
    float dl = pow(rnd, 0.38) * 0.7;
    float f = pow(clamp((depart - dl) / 0.3, 0.0, 1.0), 3.0);
    if (uFlow < 1.5) {
      // В камеру — как прыжок на скорость света: точка летит по своему лучу
      // к зрителю, и на экране слово расходится от центра, не теряя линий букв.
      P = P0;
      P.z += f * (uCamZ - P0.z + 200.0);
    } else if (uFlow < 2.5) {
      // Стяжка. Каждая точка начинает путь перед камерой, но за краем кадра,
      // и идёт к своему месту по сходящейся спирали; садится мягко. Пока
      // точка ждёт своей очереди, её не видно: со стартом внутри кадра
      // ждущие точки стояли по краям экрана застывшим кольцом. Из-за спины
      // камеры они появлялись поздно, и между уходом и прилётом зиял пустой
      // кадр. Всё в долях uBaseZ — от размера окна не зависит.
      float s = clamp((depart - rnd * 0.35) / 0.65, 0.0, 1.0);
      float g = s * s;
      vec2 out2 = normalize(P0.xy + vec2(fract(aSeed * 3.1) - 0.5, fract(aSeed * 5.7) - 0.5) * 40.0);
      vec3 S = vec3(out2 * uBaseZ * (0.85 + rnd * 0.5), uCamZ - uBaseZ * (0.47 + rnd * 0.36));
      float tw = g * (0.9 + rnd * 0.5);
      vec2 off = (S.xy - P0.xy) * g;
      off = vec2(off.x * cos(tw) - off.y * sin(tw), off.x * sin(tw) + off.y * cos(tw));
      P = vec3(P0.xy + off, mix(P0.z, S.z, g));
    } else {
      // Разлёт. Шар раскручивается вокруг вертикали всё быстрее, и точки
      // в случайный черёд уходят наружу каждая в свою случайную сторону —
      // облако редеет ровно, без видимых дорожек, и гаснет.
      float spin = depart * depart * 7.5;
      float cs = cos(spin), sn = sin(spin);
      float cz = mix(uCzA, uCzB, mc);
      vec3 r = vec3(hx * cs + hz * sn, sheet.y, -hx * sn + hz * cs);
      float u = clamp((depart - 0.08 - rnd * 0.55) / 0.37, 0.0, 1.0);
      vec3 any3 = vec3(fract(aSeed * 3.1), fract(aSeed * 5.7), fract(aSeed * 7.9)) * 2.0 - 1.0;
      vec3 dir = normalize(normalize(r + vec3(0.0001)) + any3 * 0.9 + vec3(0.0001));
      P = vec3(r.x, r.y, r.z * uDepth + cz) + dir * (u * u * (600.0 + rnd * 1400.0));
      flowFade = 1.0 - smoothstep(0.35, 1.0, u);
    }
    // Вплотную к камере точка не раздувается пятном, а гаснет — у самого
    // объектива, чтобы уходящее и прилетающее успели перекрыться.
    flowFade *= smoothstep(40.0, 220.0, uCamZ - P.z);
  }

  /* Рука работает по экрану, а не по исходной раскладке слова.

     Раньше отталкивание считалось до поворота: на развороте в 180°
     ось X смотрит в другую сторону, и точки уходили в зеркальную
     сторону от курсора — вместо магнита получался антимагнит. Теперь
     точка сперва переводится в экранные пиксели, там встречается
     с курсором, и уже сдвиг возвращается обратно в сцену. */
  float depth = max(uCamZ - P.z, 60.0);
  float persp = uBaseZ / depth;

  /* Никакого потолка сдвига здесь больше нет.

     Он и был тем «пределом», за который точка не могла отлететь, сколько
     по ней ни води: сдвиг обрезался, и повторный проход рукой ничего не
     добавлял. Теперь дальность решает сама физика на стороне JS — точка
     летит, пока её не погасит трение, и удары складываются. */
  P.xy += aDisp.xy / persp;
  P.z += aDisp.z;

  /* Живая материя: каждая точка всё время чуть шевелится сама по себе, как
     зерно в ладони, — у пингвина igloo тело «кипит» и в покое (Илья,
     2026-10-19). Своя частота и фаза у каждой точки, поэтому слово не
     дышит целиком; размах — пиксель с небольшим, и надпись читается. */
  float alivePh = aSeed * 43.0;
  float aliveFr = 1.6 + fract(aSeed * 7.31) * 1.8;
  P.xy += vec2(sin(uTime * aliveFr + alivePh), cos(uTime * aliveFr * 0.83 + alivePh * 1.7)) * 1.2 / persp;

  // Поблёскивание: у каждой точки своя редкая короткая вспышка. Степень
  // синуса держит её тёмной почти всё время — получается искра, а не
  // общая пульсация, от которой надпись «дышит» целиком и мельтешит.
  // У сетки сферы искры почти гаснут: случайные вспышки ломали ровный рисунок.
  vSpark = pow(max(0.0, sin(uTime * 0.75 + aSeed * 61.7)), 14.0) * (1.0 - uSolid * 0.85);

  /* Смаз по скорости.

     Летящая точка вытягивается вдоль своего движения и сжимается обратно,
     когда замирает. Без этого песок всё время одинаково круглый: глаз
     видит, что точки переместились, но скорости не чувствует — движение
     выходит вялым, сколько его ни усиливай. */
  float spd = length(aVel.xy);
  vStretch = 1.0 + min(spd * 0.22, 4.0);
  vDir = spd > 0.01 ? aVel.xy / spd : vec2(1.0, 0.0);
  // На лету точка ещё и разогревается: песок на скорости светлее.
  vHeat = min(spd * 0.05, 0.65);
  // Точки, которые пересаживаются волной, разгораются — по шару идёт
  // светлая полоса, и видно, что это уже другой проект (Илья, 2026-10-18).
  vHeat = max(vHeat, swapGlow * 0.9);

  /* Изнутри сетка реже: на рёбрах гаснет каждая вторая точка — по порядку,
     узлы остаются. Вплотную сетка читалась монолитной решёткой, а это
     всё-таки точки; гасить вразброс было нельзя — шаг выходил неровный,
     «как с блюдца просыпалось» (Илья, 2026-10-18). */
  float sparse = mix(1.0, step(0.75, aKeep), uSolid * smoothstep(0.4, 1.0, m));
  vFade = e * (1.0 - smoothstep(0.82, 1.0, depart)) * uVis * (1.0 - uDim) * swapVis * sparse * flowFade;
  vec4 mv = modelViewMatrix * vec4(P, 1.0);
  gl_Position = projectionMatrix * mv;
  // Точка растёт по мере приближения к камере. Без этого летящая в лицо
  // частица остаётся такой же мелкой, и полёта не чувствуется вовсе.
  // Квадрат под точку растёт вместе со штрихом, иначе он обрежется краем.
  // Раскрытая сфера далеко вокруг, и её точки в перспективе мельчают —
  // изнутри сетку было почти не видно. Крупнее — и понятно, что ты внутри.
  // У сетки точки одного размера — линия ровная; у надписей разброс
  // размеров даёт зерно.
  gl_PointSize = mix(1.35 + aSeed * 0.85, 1.9, uSolid) * uPixelRatio * clamp(persp, 0.3, 3.0)
               * (1.0 + vSpark * 0.5) * vStretch * (1.0 + uSolid * m * 1.4) * (1.0 + swapGlow * 0.6);
}`;

export const PARTICLE_FRAG = `
precision highp float;
/** Цвет точки: песок, а на сфере проекта — свет из его кадра. */
varying vec3 vBase;
varying float vMask;
varying float vFade;
varying float vSpark;
varying vec2 vDir;
varying float vStretch;
varying float vHeat;

void main(){
  // Мягкий круг вместо квадратной точки: квадраты выдают WebGL сразу.
  // В покое это круг, на скорости — капсула, вытянутая по ходу движения:
  // квадрат под точку уже увеличен, и здесь остаётся сжать координаты
  // поперёк хода, чтобы получился штрих, а не раздутое пятно.
  vec2 c = gl_PointCoord - 0.5;
  vec2 along = vec2(dot(c, vDir), dot(c, vec2(-vDir.y, vDir.x)));
  along.x /= vStretch;
  float a = 1.0 - smoothstep(0.28 / vStretch, 0.5 / vStretch, length(along));
  if (a < 0.01) discard;
  // Точки стоят плотно, и на полной непрозрачности буква заливается
  // сплошняком. Чуть прозрачнее — слово читается цельным, но видно,
  // что оно набрано из точек.
  vec3 col = mix(vBase, vec3(1.0), vSpark * 0.55 + vHeat);
  // Растянутый штрих тоньше по яркости: иначе быстрая точка выглядит
  // жирнее остальных и облако на движении выцветает в кашу.
  gl_FragColor = vec4(col, a * vFade * vMask * (0.72 + vSpark * 0.28) / (0.6 + vStretch * 0.4));
}`;

/* Среда маршрута: пыль в глубине и ориентиры на пути.

   Объекты точек собираются и рассыпаются на месте, поэтому ощущение хода
   даёт среда: пыль летит навстречу с прокруткой, а между точками
   пролетаешь сквозь фигуры — ворота перед проектами, арки на остальных
   переходах. Один шейдер на всё: у пыли глубина бежит по кругу (uWrap),
   у ориентира она общая на фигуру (uZ). */
export const DUST_VERT = `
precision highp float;
attribute vec3 aPos;
attribute float aSeed;
uniform float uTime;
uniform float uPixelRatio;
uniform float uCamZ;
uniform float uBaseZ;
/** Пыль: сдвиг потока и его длина. Точка, ушедшая за камеру, снова
    появляется вдали — поток бесконечный, а на кольце маршрута без шва. */
uniform float uShift;
uniform float uLen;
uniform float uWrap;
/** Ориентир: где по глубине стоит вся фигура. */
uniform float uZ;
/** Где фигура гаснет вдали, в единицах сцены. */
uniform float uFar;
uniform float uAlpha;
/** Скорость маршрута 0..1: на ходу пыль чуть крупнее. */
uniform float uSpeed;
/** Вода, которую мешает рука: пыль — взвесь в ней, её уносит течением. */
uniform sampler2D uWaterTex;
uniform vec4 uWaterMap;
varying float vA;
varying float vSeed;

void main(){
  vec3 p = aPos;
  float z = uWrap > 0.5 ? uCamZ - uLen + mod(p.z + uShift, uLen) : uZ + p.z;
  // Пыль сама по себе чуть плывёт — мир живой и в покое.
  p.x += sin(uTime * 0.05 + aSeed * 31.0) * 8.0;
  p.y += cos(uTime * 0.04 + aSeed * 17.0) * 8.0;
  float depth = uCamZ - z;
  float persp = uBaseZ / max(depth, 1.0);
  /* Там, где пылинка видна на экране, вода сдвинута рукой — сдвигаем и её,
     в пикселях экрана. Дальние уходят чуть меньше: толща между ними
     и рукой гасит течение. */
  vec4 sp = projectionMatrix * modelViewMatrix * vec4(p.x, p.y, z, 1.0);
  vec2 suv = sp.xy / max(sp.w, 1.0) * 0.5 + 0.5;
  vec4 wv = texture2D(uWaterTex, suv * uWaterMap.xy + uWaterMap.zw);
  p.xy += wv.xy / persp * clamp(persp, 0.4, 1.0);
  float far = 1.0 - smoothstep(uFar * 0.55, uFar, depth);
  // Точка у самого объектива — клякса во весь экран: гасим заранее.
  float near = smoothstep(uBaseZ * 0.06, uBaseZ * 0.3, depth);
  vA = uAlpha * far * near * (0.35 + aSeed * 0.65);
  // В течении частица ловит свет и вспыхивает — видно, где прошла рука.
  vA *= 1.0 + min(wv.a / 8.0, 1.0) * 1.5;
  vSeed = aSeed;
  gl_Position = projectionMatrix * modelViewMatrix * vec4(p.x, p.y, z, 1.0);
  gl_PointSize = clamp((0.9 + aSeed * 1.4) * persp, 0.6, 5.0) * uPixelRatio * (1.0 + uSpeed);
}`;

export const DUST_FRAG = `
precision highp float;
uniform vec3 uSand;
uniform vec3 uAzure;
varying float vA;
varying float vSeed;

void main(){
  vec2 c = gl_PointCoord - 0.5;
  float a = (1.0 - smoothstep(0.2, 0.5, length(c))) * vA;
  if (a < 0.003) discard;
  gl_FragColor = vec4(mix(uAzure, uSand, vSeed), a);
}`;
